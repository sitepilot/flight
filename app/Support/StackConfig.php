<?php

declare(strict_types=1);

namespace App\Support;

use App\Exceptions\FlightException;
use App\Recipes\Recipe;
use App\Services\PhpService;
use Illuminate\Contracts\Container\Container;
use Illuminate\Support\Facades\Validator;
use Symfony\Component\Yaml\Exception\ParseException;
use Symfony\Component\Yaml\Yaml;

/**
 * A stack's YAML file: a few settings, an app and services, merged over a
 * recipe. Only the shape of each service is checked here; each service
 * validates its own options.
 */
abstract class StackConfig
{
    public const string APP = 'app';

    protected ?array $settings = null;

    protected ?Recipe $recipe = null;

    protected ?array $ownComposeFiles = null;

    /**
     * Where each service with `x-flight` is set, by Flight name, e.g.
     * `['path' => 'services.web.x-flight', 'file' => '/…/compose.yml']`.
     */
    protected array $extensions = [];

    public function __construct(protected Container $container) {}

    abstract public function file(): string;

    abstract public function stackName(): string;

    abstract public function directory(): string;

    /**
     * The compose project directory, where compose resolves paths and reads
     * .env: the folder of the first file listed under `compose`, as for
     * `docker compose -f`, or else the config's.
     */
    public function projectDirectory(): string
    {
        $files = $this->ownComposeFiles();

        return $files === [] ? $this->directory() : dirname($files[0]);
    }

    public function filesDirectory(): string
    {
        return $this->directory().'/.flight';
    }

    abstract public function label(string $service): string;

    /**
     * For the settings other than the services.
     */
    abstract protected function rules(): array;

    /**
     * As written: a name, a mapping of one name to its options, or null.
     */
    abstract protected function recipeSetting(array $settings): mixed;

    protected function messages(): array
    {
        return [];
    }

    protected function withDefaults(array $settings): array
    {
        return $settings;
    }

    public function composeFile(): string
    {
        return $this->filesDirectory().'/compose.yaml';
    }

    public function composeNote(): string
    {
        return 'change '.basename($this->file()).', or list your own compose files under `compose` in it.';
    }

    public function prepare(): void
    {
        Files::put($this->filesDirectory().'/.gitignore', "# Generated by flight.\n*\n");
    }

    /**
     * Variables compose files can use.
     */
    public function environment(): array
    {
        return [];
    }

    /**
     * The files listed under `compose` that exist. They run after the
     * generated file, so they can change what Flight generates.
     */
    public function ownComposeFiles(): array
    {
        $this->load();

        return $this->ownComposeFiles;
    }

    /**
     * Where a service is set, e.g. "app", "services.db", or
     * "services.web.x-flight" in a compose file.
     */
    public function servicePath(string $name): string
    {
        return $this->extensions[$name]['path'] ?? ($name === self::APP ? self::APP : "services.{$name}");
    }

    /**
     * The other stacks join the shared network as an external network.
     */
    public function ownsNetwork(): bool
    {
        return false;
    }

    public function recipe(): ?Recipe
    {
        $this->load();

        return $this->recipe;
    }

    public function services(): array
    {
        return $this->load()['services'];
    }

    protected function get(string $key): mixed
    {
        return $this->load()[$key] ?? null;
    }

    public function load(): array
    {
        if ($this->settings !== null) {
            return $this->settings;
        }

        $settings = $this->composeShorthand($this->withDefaults($this->read()));

        $this->validate($settings);

        $this->ownComposeFiles = $this->existingComposeFiles($settings['compose'] ?? []);

        $this->recipe = $this->makeRecipe($this->recipeSetting($settings));

        // A string is short for its type: `db: mariadb:11.8`.
        $shorthand = fn (mixed $entry): mixed => is_string($entry) ? ['type' => $entry] : $entry;

        $services = array_map($shorthand, (array) ($settings['services'] ?? []));
        $file = $shorthand($settings[self::APP] ?? null);

        foreach ($services as $name => $options) {
            $this->ensureRecipeType("services.{$name}", $this->recipe?->services()[$name] ?? null, $options);
        }

        $this->ensureRecipeType(self::APP, $this->recipe?->app(), $file);

        $merged = $this->merge($this->recipe?->services() ?? [], $services);

        if (array_key_exists(self::APP, $merged)) {
            throw $this->invalid('Expected another name; "app" is the app, set at the top level as `app:`.', 'services.'.self::APP);
        }

        if ($file !== null && ! $this->isMap($file)) {
            throw $this->invalid('Expected app to be a type such as `php:8.4`, or a mapping with a type.', self::APP);
        }

        if ($this->recipe?->app() !== null || $file !== null) {
            $merged = [self::APP => $this->merge($this->recipe?->app() ?? [], (array) $file), ...$merged];
        }

        $services = [];

        foreach ($merged as $name => $options) {
            $services[$name] = $this->service((string) $name, $options);
        }

        foreach ($this->composeExtensions($this->ownComposeFiles) as $name => $options) {
            if (array_key_exists($name, $services)) {
                $where = $name === self::APP ? '`app:`' : "services.{$name}";

                throw $this->invalid("Expected \"{$name}\" in one place: {$where} in ".basename($this->file()).', or x-flight here.', $this->servicePath($name));
            }

            $services = $name === self::APP ? [$name => $options, ...$services] : [...$services, $name => $options];
        }

        if ($services === []) {
            throw $this->invalid('Expected a service, such as `app: php:8.4`, or `x-flight` on a service in your compose files.');
        }

        return $this->settings = [...$settings, 'services' => $services];
    }

    protected function existingComposeFiles(array $files): array
    {
        $existing = [];

        foreach ($files as $i => $file) {
            $path = $this->directory().'/'.$file['path'];

            if (is_file($path)) {
                $existing[] = $path;
            } elseif ($file['required']) {
                throw $this->invalid("Expected {$file['path']} to exist, or to be marked `required: false`.", "compose.{$i}");
            }
        }

        return $existing;
    }

    /**
     * The services with `x-flight` in the own compose files, keyed by their
     * Flight name. When a service has `x-flight` in several files, the one
     * in the file listed last is used as a whole, not merged. Values are
     * read as written: compose's variables aren't filled in.
     */
    protected function composeExtensions(array $files): array
    {
        $found = [];

        foreach ($files as $file) {
            try {
                $parsed = Yaml::parseFile($file);
            } catch (ParseException $e) {
                throw FlightException::make("Could not parse {$file}.", $e->getMessage());
            }

            foreach ((array) (is_array($parsed) ? $parsed['services'] ?? [] : []) as $service => $definition) {
                if (is_array($definition) && array_key_exists('x-flight', $definition)) {
                    $found[(string) $service] = [$file, $definition['x-flight']];
                }
            }
        }

        $services = [];

        foreach ($found as $service => [$file, $options]) {
            $path = "services.{$service}.x-flight";

            // Registered first, so errors below name the compose file.
            $this->extensions[$service] = ['path' => $path, 'file' => $file];

            if (! $this->isMap($options)) {
                throw $this->invalid("Expected where the proxy reaches the service, such as `origin: https://{$service}:8443`.", $path);
            }

            $app = $this->hasApp() && ($options['app'] ?? $service === self::APP) === true;

            if ($app && isset($services[self::APP])) {
                throw $this->invalid('Expected one app, but '.$this->extensions[self::APP]['path'].' is the app too.', $path);
            }

            if (! $app && ! preg_match('/^[a-z0-9][a-z0-9_-]*$/', $service)) {
                throw $this->invalid('Expected a lowercase service name such as "web"'.($this->hasApp() ? ', or `app: true` to make it the app.' : '.'), $path);
            }

            // The proxy's labels go on the service the origin names.
            if (is_string($options['origin'] ?? null) && parse_url($options['origin'], PHP_URL_HOST) !== $service) {
                throw $this->invalid("Expected the origin to name this service, such as \"https://{$service}:8443\".", "{$path}.origin");
            }

            if ($app) {
                unset($this->extensions[$service]);
                $this->extensions[self::APP] = ['path' => $path, 'file' => $file];
            }

            if ($this->hasApp()) {
                unset($options['app']);
            }

            $services[$app ? self::APP : $service] = ['type' => 'compose', ...$options];
        }

        return $services;
    }

    /**
     * Whether a service with `x-flight` can be the app, by its name or with
     * `app: true`.
     */
    protected function hasApp(): bool
    {
        return true;
    }

    /**
     * Keep the recipe's type, so the recipe's options still fit: `php:8.5`
     * over the recipe's `php` is fine, `mariadb` is not.
     */
    protected function ensureRecipeType(string $path, mixed $recipe, mixed $file): void
    {
        $base = fn (mixed $options): ?string => is_string($options['type'] ?? null)
            ? explode(':', $options['type'])[0]
            : null;

        $expected = is_array($recipe) ? $base($recipe) : null;
        $actual = is_array($file) ? $base($file) : null;

        if ($expected !== null && $actual !== null && $expected !== $actual) {
            throw $this->invalid("Expected {$expected}, as set by the {$this->recipe?->name()} recipe; you can change its version, such as `{$expected}:<version>`.", "{$path}.type");
        }
    }

    /**
     * The version is split from the type: `type: mariadb:11.8` becomes the
     * type "mariadb" and the version "11.8".
     */
    protected function service(string $name, mixed $options): array
    {
        $app = $name === self::APP;
        $path = $app ? self::APP : "services.{$name}";
        $example = $app ? 'php:8.4' : 'mariadb:11.8';

        if (! $app && ! preg_match('/^[a-z0-9][a-z0-9_-]*$/', $name)) {
            throw $this->invalid('Expected a lowercase service name such as "db".', $path);
        }

        if (! $this->isMap($options)) {
            throw $this->invalid("Expected a type such as `{$example}`, or a mapping with a type.", $path);
        }

        if (array_key_exists('version', $options)) {
            throw $this->invalid("Expected the version in the type, such as `type: {$example}`.", "{$path}.version");
        }

        // Compose services come from `x-flight` in the compose files.
        $types = $app ? (array) config('flight.app_types') : array_diff(array_keys((array) config('flight.services')), ['compose']);
        $type = $options['type'] ?? null;

        if (! is_string($type) || ! preg_match('/^([a-z0-9_-]+)(?::([A-Za-z0-9._-]+))?$/', $type, $match) || ! in_array($match[1], $types, true)) {
            throw $this->invalid("Expected a type such as `{$example}`, one of: ".implode(', ', $types).'.', "{$path}.type");
        }

        unset($options['type']);

        return ['type' => $match[1], ...(isset($match[2]) ? ['version' => $match[2]] : []), ...$options];
    }

    protected function read(): array
    {
        if (! is_file($this->file())) {
            return [];
        }

        try {
            $parsed = Yaml::parseFile($this->file());
        } catch (ParseException $e) {
            throw FlightException::make('Could not parse '.$this->file().'.', $e->getMessage());
        }

        if ($parsed !== null && ! is_array($parsed)) {
            throw $this->invalid('Expected a mapping of settings.');
        }

        return (array) $parsed;
    }

    protected function makeRecipe(mixed $setting): ?Recipe
    {
        if ($setting === null) {
            return null;
        }

        if (is_string($setting)) {
            [$name, $options] = [$setting, []];
        } elseif ($this->isMap($setting) && count($setting) === 1) {
            $name = (string) array_key_first($setting);
            $options = $setting[$name] ?? [];
        } else {
            throw $this->invalid('Expected a recipe such as "laravel", or one recipe with its options, such as `laravel: {}`.', 'recipe');
        }

        $recipes = (array) config('flight.recipes');

        if (! isset($recipes[$name])) {
            throw $this->invalid('Expected recipe to be one of: '.implode(', ', array_keys($recipes)).'.', 'recipe');
        }

        if (! $this->isMap($options)) {
            throw $this->invalid('Expected a mapping of options.', "recipe.{$name}");
        }

        return $this->container->make($recipes[$name], ['config' => $this, 'name' => $name, 'options' => $options]);
    }

    /**
     * Mappings merge key by key, anything else is replaced. A null option,
     * such as a bare `php:`, keeps the recipe's value.
     */
    protected function merge(array $base, array $override): array
    {
        foreach ($override as $key => $value) {
            $current = $base[$key] ?? null;

            if ($value === null && array_key_exists($key, $base)) {
                continue;
            }

            $base[$key] = $this->isMap($current) && $this->isMap($value)
                ? $this->merge($current, $value)
                : $value;
        }

        return $base;
    }

    protected function isMap(mixed $value): bool
    {
        return is_array($value) && ($value === [] || ! array_is_list($value));
    }

    protected function composeShorthand(array $settings): array
    {
        if (is_array($settings['compose'] ?? null)) {
            $settings['compose'] = array_map(fn (mixed $file): mixed => match (true) {
                is_string($file) => ['path' => $file, 'required' => true],
                is_array($file) => [...$file, 'required' => $file['required'] ?? true],
                default => $file,
            }, $settings['compose']);
        }

        return $settings;
    }

    protected function validate(array $settings): void
    {
        $rules = [
            'services' => ['nullable', 'array'],
            ...$this->rules(),
            'compose' => ['nullable', 'list'],
            'compose.*' => ['array:path,required'],
            'compose.*.path' => ['required', 'string', 'regex:'.PhpService::PATH],
            'compose.*.required' => ['boolean'],
        ];

        $topLevel = array_filter(array_keys($rules), fn (string $key): bool => ! str_contains($key, '.'));

        foreach (array_keys($settings) as $key) {
            if (! in_array($key, $topLevel, true)) {
                throw $this->invalid('Expected one of: '.implode(', ', $topLevel).'.', (string) $key);
            }
        }

        // Name attributes after the YAML keys, e.g. "http_port" instead of
        // "http port".
        $keys = array_filter(array_keys($rules), fn (string $key): bool => ! str_contains($key, '*'));

        $validator = Validator::make($settings, $rules, [
            'services.array' => 'Expected services to be a mapping of names to types, such as `db: mariadb:11.8`.',
            'compose.list' => 'Expected the compose files to run, such as [compose.yml].',
            'compose.*.array' => 'Expected a file such as "compose.yml", or one that may be missing, such as `{path: compose.override.yml, required: false}`.',
            'compose.*.path.regex' => 'Expected a path inside the folder of '.basename($this->file()).', such as "compose.yml".',
            ...$this->messages(),
        ], attributes: array_combine($keys, $keys));

        if ($validator->fails()) {
            $key = (string) array_key_first($validator->errors()->messages());

            throw $this->invalid((string) $validator->errors()->first($key), $key);
        }

        $services = $settings['services'] ?? [];

        if ($services !== [] && array_is_list($services)) {
            throw $this->invalid('Expected services to be a mapping of names to types, such as `db: mariadb:11.8`.', 'services');
        }
    }

    /**
     * A key under a service's `x-flight` is named in its compose file.
     */
    public function invalid(string $hint, ?string $key = null): FlightException
    {
        $file = $this->file();

        foreach ($this->extensions as ['path' => $path, 'file' => $source]) {
            if ($key === $path || str_starts_with((string) $key, $path.'.')) {
                $file = $source;
            }
        }

        return FlightException::make(
            $key === null ? "Invalid {$file}." : "Invalid \"{$key}\" in {$file}.",
            $hint,
        );
    }
}
